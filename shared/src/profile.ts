/**
 * Правила заполнения профиля (ТЗ §3).
 *
 * Телефон проверяют трое: форма регистрации, DTO `PATCH /profile` и (косвенно)
 * seed. Правило одно на всех — иначе форма пропустит то, что отклонит API.
 */

/**
 * Столько символов принимается в телефоне.
 *
 * Это договорённость приложения, а не свойство базы: колонка `User.phone`
 * объявлена как `text`, без верхней границы. Держат предел трое —
 * форма регистрации, DTO `PATCH /profile` и триггер `handle_auth_user_upsert`.
 */
export const PHONE_MAX_LENGTH = 30;

/**
 * Пределы длины текстовых полей профиля.
 *
 * В базе эти колонки объявлены как `text`, без верхней границы, — предел задаёт
 * приложение. Проверяют его двое: DTO `PATCH /profile` и триггер
 * `handle_auth_user_upsert`, через который профиль создаётся при регистрации
 * (`signUp` идёт мимо backend, и другой серверной точки проверки на этом пути нет).
 * Числа держим здесь, чтобы миграция и DTO не разъехались молча.
 */
export const PROFILE_LIMITS = {
  firstName: 100,
  lastName: 100,
  city: 100,
  country: 100,
  companyName: 200,
  phone: PHONE_MAX_LENGTH,
} as const;

/** Сколько цифр должно быть в номере: от местного семизначного с кодом до международного. */
export const PHONE_DIGITS = { min: 10, max: 15 } as const;

/**
 * Телефон: необязательный `+`, дальше только цифры, пробелы, скобки и дефисы,
 * а всего цифр — от 10 до 15 (просмотр вперёд в начале выражения).
 *
 * Строже проверять нельзя: формат номера различается по странам, а ТЗ §3
 * хранит его строкой как есть.
 */
export const PHONE_PATTERN = /^(?=(?:\D*\d){10,15}\D*$)\+?[\d\s()-]+$/;

/** Сообщение об ошибке общее для формы и API: пользователь видит одно и то же. */
export const PHONE_ERROR_MESSAGE =
  'Телефон указан неверно. Пример: +7 900 000-00-00';

export function isValidPhone(value: string): boolean {
  return value.length <= PHONE_MAX_LENGTH && PHONE_PATTERN.test(value);
}
