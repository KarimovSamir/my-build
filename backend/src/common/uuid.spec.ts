import { randomUUID } from 'node:crypto';
import { describe, expect, it } from 'vitest';

import { isUuid } from './uuid.js';

/**
 * Задача проверки — не пустить в Postgres то, что он не приведёт к типу `uuid`.
 * Версия и вариант значения при этом не важны: их сузило прежнее выражение,
 * и валидный UUIDv7 давал бы 404 (находка R1-Н1).
 */
describe('isUuid', () => {
  it('принимает то, что выдаёт сама платформа', () => {
    expect(isUuid(randomUUID())).toBe(true);
  });

  it.each([
    ['v4', '6f1c7a0e-0000-4000-8000-000000000001'],
    ['v7', '01997a4c-7d3b-7c8f-a0b1-2c3d4e5f6071'],
    ['нулевой', '00000000-0000-0000-0000-000000000000'],
    ['верхний регистр', '6F1C7A0E-0000-4000-8000-000000000001'],
  ])('принимает %s', (_case, value) => {
    expect(isUuid(value)).toBe(true);
  });

  it.each([
    ['пустая строка', ''],
    ['слово', 'не-uuid'],
    ['без дефисов', '6f1c7a0e00004000800000000000001'],
    ['лишний символ', '6f1c7a0e-0000-4000-8000-0000000000011'],
    ['недопустимая цифра', '6f1c7a0g-0000-4000-8000-000000000001'],
    ['с пробелом по краю', ' 6f1c7a0e-0000-4000-8000-000000000001'],
    ['перевод строки в конце', '6f1c7a0e-0000-4000-8000-000000000001\n'],
  ])('отклоняет %s', (_case, value) => {
    expect(isUuid(value)).toBe(false);
  });
});
