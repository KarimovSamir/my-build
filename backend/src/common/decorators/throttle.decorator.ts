import { SetMetadata } from '@nestjs/common';

export const THROTTLE_KEY = 'mybuild:throttle';

/** Сколько запросов и за какое окно разрешено одному пользователю на маршруте. */
export interface ThrottleOptions {
  /** Максимум запросов за окно. */
  limit: number;
  /** Длина окна в миллисекундах. */
  ttl: number;
}

/**
 * Ограничение частоты запросов к маршруту (ТЗ §6).
 *
 * Работает только вместе с `@UseGuards(ThrottleGuard)`: потолок задаётся
 * маршруту, а не приложению. Глобального значения нет намеренно — цена
 * запросов разная, и один лимит на всех либо не защищает ленту заказов,
 * либо срабатывает на счётчике непрочитанных при обычной работе.
 *
 * Мутирующие маршруты обязаны быть под ограничителем (ТЗ §6), читающие —
 * те, что чего-то стоят: выборка со счётчиком и поиском, обращение
 * к Supabase Storage, выдача контактов. Дешёвых читающих маршрутов без
 * ограничителя в проекте не осталось.
 */
export const Throttle = (options: ThrottleOptions) => SetMetadata(THROTTLE_KEY, options);
