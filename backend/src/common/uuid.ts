/**
 * Проверка идентификатора до похода в базу.
 *
 * Колонки `id` объявлены как `uuid`, и мусор в значении Postgres не приводит,
 * а роняет запрос: наружу уходит 500 вместо честного «не найдено». Поэтому
 * всё, что пришло от пользователя, проверяется здесь — и в guard'ах, и там,
 * где идентификатор попадает в сырой SQL.
 */

/**
 * Версия и вариант намеренно не проверяются: задача этой проверки — не пустить
 * в Postgres то, что он не приведёт к типу `uuid`, а он принимает любые
 * 32 шестнадцатеричные цифры в такой расстановке дефисов. Требование «версия
 * 1–5» отвергало бы валидный UUIDv7 и нулевой UUID, то есть давало бы 404
 * на идентификаторе, который база считает нормальным.
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: string): boolean {
  return UUID.test(value);
}
