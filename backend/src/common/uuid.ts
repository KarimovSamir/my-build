/**
 * Проверка идентификатора до похода в базу.
 *
 * Колонки `id` объявлены как `uuid`, и мусор в значении Postgres не приводит,
 * а роняет запрос: наружу уходит 500 вместо честного «не найдено». Поэтому
 * всё, что пришло от пользователя, проверяется здесь — и в guard'ах, и там,
 * где идентификатор попадает в сырой SQL.
 */

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function isUuid(value: string): boolean {
  return UUID.test(value);
}
