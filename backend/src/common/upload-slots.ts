/**
 * Сколько запросов с файлами процесс принимает одновременно.
 *
 * Multer пишет тело запроса во временный каталог, и каждый принятый запрос —
 * это до `MAX_UPLOAD_REQUEST_BYTES` на диске плюс чтение с хешированием.
 * Ограничитель частоты считает по пользователю (у демо-учётки — по сессии,
 * а новую сессию даёт обычный повторный вход), поэтому общий потолок
 * на процесс нужен отдельно: без него скрипт с десятком сессий забивал бы
 * временный диск и канал единственного инстанса.
 *
 * В отличие от семафора загрузок в бакет (`Semaphore`), лишний запрос здесь
 * не ждёт, а сразу получает отказ: ждать ему пришлось бы, держа открытое
 * соединение с телом, которое уже едет по сети.
 *
 * Живёт в памяти процесса — как очередь заказа и резерв квоты (один
 * экземпляр backend — условие деплоя).
 */
export class UploadSlots {
  private active = 0;

  constructor(readonly limit: number) {
    if (limit < 1) {
      throw new RangeError('UploadSlots: предел должен быть не меньше 1');
    }
  }

  /** Занять место. `null` — мест нет; иначе освобождение, которое можно звать сколько угодно раз. */
  tryAcquire(): (() => void) | null {
    if (this.active >= this.limit) {
      return null;
    }

    this.active += 1;
    let released = false;

    return () => {
      if (released) return;
      released = true;
      this.active -= 1;
    };
  }

  get inUse(): number {
    return this.active;
  }
}

/**
 * Три запроса по 51 МБ — около 150 МБ временного диска в худшем случае.
 * Обычной работе этого хватает с запасом: загрузка — редкое действие,
 * и отказ «повторите» при совпадении трёх загрузок разом лучше, чем
 * инстанс без места на диске.
 */
export const MAX_CONCURRENT_UPLOAD_REQUESTS = 3;

export const uploadSlots = new UploadSlots(MAX_CONCURRENT_UPLOAD_REQUESTS);
