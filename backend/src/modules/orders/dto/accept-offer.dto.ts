import { IsISO8601, ValidateIf } from 'class-validator';

/**
 * `POST /orders/:id/accept-offer/:offerId` — какую версию предложения клиент
 * видел, нажимая «Принять». ТЗ §5 тела у маршрута не предусматривает
 * (отступление — `CLAUDE.md` §7).
 *
 * Цена и срок сделки берутся из строки предложения в момент принятия, а
 * компания вправе переписать его в любую секунду (ТЗ §4.1). Без этого поля
 * клиент, у которого карточка не успела обновиться, соглашался бы на цену,
 * которой не видел.
 *
 * Поле обязательное: `null` — «условия не меняли с отправки» (`editedAt`
 * предложения пуст), а отсутствующий ключ — ошибка, а не «проверять не надо».
 */
export class AcceptOfferDto {
  @ValidateIf((dto: AcceptOfferDto) => dto.offerEditedAt !== null)
  @IsISO8601(
    { strict: true },
    { message: 'Не передано, какую версию предложения вы принимаете. Обновите страницу' },
  )
  offerEditedAt!: string | null;
}
