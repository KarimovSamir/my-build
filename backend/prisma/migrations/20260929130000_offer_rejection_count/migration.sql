-- Сколько раз клиент отклонил предложение (решение пользователя).
--
-- ТЗ §4.1 разрешает компании присылать отклонённое предложение заново без
-- предела, и клиенту нечем остановить ту, которой он уже отказал. Теперь
-- повтор после отказа один: после второго отказа отклонение окончательное
-- (`MAX_OFFER_REJECTIONS` в shared/src/offers.ts). Счётчик нужен отдельной
-- колонкой: статус `REJECTED` после первого и после второго отказа один и тот же.
ALTER TABLE "Offer" ADD COLUMN "rejectionCount" INTEGER NOT NULL DEFAULT 0;

-- Уже отклонённые предложения отклонены по меньшей мере один раз.
UPDATE "Offer" SET "rejectionCount" = 1 WHERE "status" = 'REJECTED';
