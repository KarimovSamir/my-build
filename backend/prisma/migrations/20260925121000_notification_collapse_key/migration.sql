-- Повторные события об одном и том же не копятся в колокольчике.
--
-- Каждое сохранение предложения — и правка, и повторная отправка после
-- отзыва — создавало клиенту новое «Новое предложение»: одна компания могла
-- положить их десятки в минуту, а таблица росла без предела. То же с файлами
-- сдачи и уточнением площади у исполнителя.
--
-- Уведомление получает ключ «о чём оно». Непрочитанное с тем же адресатом
-- и ключом заменяется новым: у адресата остаётся одно — с последним
-- состоянием. Прочитанные не трогаются — это история.
--
-- Отдельного индекса нет: поиск идёт по `userId` + `isRead = false`, это уже
-- покрывает индекс списка, а непрочитанных у одного адресата немного — это
-- схлопывание и держит.
