-- Разбор аудита Фазы 4 (низкая находка 11): компания, чьё предложение проиграло
-- выбор, получала уведомление с заголовком «Предложение отклонено», хотя её
-- предложение уходит в OfferStatus.NOT_ACCEPTED — «Не выбрано». Клиент это
-- предложение не отклонял, он выбрал другое, и заголовок был неправдой.
--
-- Основание ровно то же, по которому 4 сентября 2026 завели OFFER_WITHDRAWN:
-- заголовок уведомления берётся из его типа, и переиспользовать чужой тип
-- значит показать пользователю не то событие, которое произошло.
--
-- Значения OFFER_NOT_ACCEPTED в списке NotificationType из ТЗ §3 нет —
-- отступление принято пользователем 5 сентября 2026 и записано в CLAUDE.md §7.
--
-- Отдельной миграцией, а не вместе с другими правками: ALTER TYPE ... ADD VALUE
-- добавляет значение, которым нельзя пользоваться до конца транзакции, а файл
-- миграции Prisma выполняет целиком в одной.

ALTER TYPE "NotificationType" ADD VALUE IF NOT EXISTS 'OFFER_NOT_ACCEPTED';
