-- Ревизия после закрытия audit.md (находка R1-С1): отзыв предложения возвращает
-- заказ в поиск исполнителя, то есть меняет его статус чужими руками, а клиент
-- об этом не узнавал — уведомление при таком переходе не создавалось вовсе.
-- ТЗ §8 требует, чтобы событие, адресованное конкретному пользователю,
-- одновременно создавало запись Notification.
--
-- Ни один из прежних типов сюда не подходил: «Предложение отклонено»
-- (OFFER_REJECTED) описывает действие самого клиента, и показывать этот
-- заголовок при отзыве со стороны компании было бы неправдой.
--
-- Значения OFFER_WITHDRAWN в списке NotificationType из ТЗ §3 нет — отступление
-- принято пользователем 4 сентября 2026 и зафиксировано в CLAUDE.md §6.
--
-- Отдельной миграцией, а не вместе с проверками профиля: ALTER TYPE ... ADD VALUE
-- добавляет значение, которым нельзя пользоваться до конца транзакции.

ALTER TYPE "NotificationType" ADD VALUE IF NOT EXISTS 'OFFER_WITHDRAWN';
