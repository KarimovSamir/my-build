-- Клиент вправе удалить заказ, пока работы не начались (ТЗ §4.1), и вместе
-- с заказом каскадом уходят предложения компаний. До сих пор компания просто
-- переставала видеть своё предложение в «Моих предложениях» и не узнавала,
-- что произошло. Уведомление об этом было отложено до Фазы 5 (CLAUDE.md §7).
--
-- Тип свой, а не переиспользованный: заголовок уведомления берётся из типа,
-- а «Предложение отклонено» и «Предложение не выбрано» описывают выбор,
-- которого не было. Основание то же, по которому заведены OFFER_WITHDRAWN
-- и OFFER_NOT_ACCEPTED.
--
-- Значения ORDER_DELETED в списке NotificationType из ТЗ §3 нет — отступление
-- принято пользователем 5 сентября 2026 и записано в CLAUDE.md §7.
--
-- Отдельной миграцией, а не вместе с правкой внешнего ключа: ALTER TYPE ...
-- ADD VALUE добавляет значение, которым нельзя пользоваться до конца
-- транзакции, а файл миграции Prisma выполняет целиком в одной.

ALTER TYPE "NotificationType" ADD VALUE IF NOT EXISTS 'ORDER_DELETED';
