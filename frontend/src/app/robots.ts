import type { MetadataRoute } from "next";

/**
 * Демо закрыто от поисковых систем целиком.
 *
 * Причина не техническая, а содержательная: приложение работает на seed-данных.
 * «ООО СтройГрад», «Ремонт Плюс», заказы и суммы в них выдуманы. Пока адрес был
 * безымянным `*.vercel.app`, индексация ничего не значила; на поддомене бренда
 * (mybuild.mydigitalhome.me) проиндексированные фальшивые заказы читались бы как
 * настоящие работы и настоящие клиенты студии.
 *
 * Ранжироваться должна страница кейса на основном сайте, а не демо.
 *
 * Этот файл отдаёт /robots.txt. Мета-тег `noindex` ставится отдельно, в
 * `metadata.robots` корневого layout: robots.txt запрещает обход, но уже
 * известный поисковику адрес может остаться в выдаче без него.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: { userAgent: "*", disallow: "/" },
  };
}
