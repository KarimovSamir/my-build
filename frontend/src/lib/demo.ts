/**
 * Подписи для общих демо-учёток с экрана входа.
 *
 * Одна фраза на все места, где демо чего-то не даёт: профиль, пароль,
 * экран нового пароля. Разные объяснения одного запрета читались бы как
 * три разных правила.
 */
/**
 * Каких сессий касается «Выйти».
 *
 * Обычная учётка выходит на всех устройствах (ТЗ §5). Демо — только на этом:
 * ею одновременно пользуются все посетители, и `global` отзывал бы их
 * refresh-токены — через час после чужого выхода их выкидывало бы на вход.
 */
export function signOutScope(isDemo: boolean): "global" | "local" {
  return isDemo ? "local" : "global";
}

