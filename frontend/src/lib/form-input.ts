/**
 * Разбор того, что пользователь вводит руками: числа с запятой и календарные
 * даты.
 *
 * Живёт отдельно от конкретных форм, потому что правила общие: заказ и
 * предложение спрашивают и сумму, и дату «не раньше сегодня», и разъехавшись
 * они вели бы себя по-разному на одинаковых полях.
 *
 * Модуль чистый — ни React, ни fetch.
 */

/**
 * Запятая в числе — привычный десятичный разделитель, backend ждёт точку.
 *
 * Заменяются все запятые, а не первая: «1,234,5» иначе превращалось бы
 * в «1.234,5» и отсекалось сообщением про формат, хотя причина в другом.
 * Строка с несколькими разделителями всё равно не пройдёт проверку —
 * но по понятному правилу, а не по остатку от замены.
 */
export function normalizeNumber(value: string): string {
  return value.trim().replaceAll(",", ".");
}

/**
 * Сегодняшний день по UTC в виде `ГГГГ-ММ-ДД`.
 *
 * Именно по UTC, а не по часовому поясу браузера: с этой же границей сравнивает
 * дату backend (`IsNotPastDate`), и разойдись они — календарь предлагал бы
 * день, который сервер отклонит.
 */
export function todayIsoDate(): string {
  return new Date().toISOString().slice(0, 10);
}

/** Строка вида `ГГГГ-ММ-ДД` — то, что отдаёт календарь и принимает API. */
export function isCalendarDate(value: string): boolean {
  return /^\d{4}-\d{2}-\d{2}$/.test(value);
}

/** Календарная дата раньше сегодняшнего дня. Сравнение строк — даты одного вида. */
export function isPastDate(value: string): boolean {
  return value < todayIsoDate();
}
