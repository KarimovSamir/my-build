/**
 * Что написать компании-исполнителю о её работе по заказу (ТЗ §4.1).
 *
 * Кнопки говорят, что можно нажать, но не говорят, почему нажать нельзя:
 * «Сдать работу» не появляется, пока в текущей сдаче нет ни одного файла,
 * и без текста это выглядело бы поломкой. Подсказка живёт отдельно от разметки,
 * чтобы каждый статус проверялся тестом, а не глазами.
 *
 * Ветки `default` нет намеренно: перечислены все статусы, и новый не соберётся,
 * пока ему не напишут текст.
 *
 * Модуль чистый — ни React, ни fetch.
 */

import { OrderStatus } from "@/lib/types";

/**
 * Строка над кнопками компании. `null` — блока работы на странице нет вовсе:
 * до принятия предложения работать не над чем.
 */
export function workHint(
  status: OrderStatus,
  /** Есть ли файлы в сдаче, которая ещё не отправлена клиенту. */
  hasOpenFiles: boolean,
): string | null {
  switch (status) {
    case OrderStatus.WAITING:
    case OrderStatus.AWAITING_CONFIRMATION:
      return null;

    case OrderStatus.IN_PROGRESS:
      return hasOpenFiles
        ? "Файлы загружены. Когда работа готова, сдайте её клиенту на подтверждение."
        : "Загрузите файлы работы с комментарием — после этого заказ можно будет сдать клиенту.";

    case OrderStatus.AWAITING_COMPLETION_CONFIRMATION:
      return "Работа передана клиенту и ждёт его решения. Добавить файлы можно будет, если он вернёт её на доработку.";

    case OrderStatus.COMPLETION_DISPUTED:
      return hasOpenFiles
        ? "Исправленные файлы загружены. Сдайте работу заново — клиент увидит новую сдачу."
        : "Клиент вернул работу на доработку. Загрузите исправленные файлы новой сдачей.";

    case OrderStatus.COMPLETED:
      return "Заказ завершён. Файлы сдач остаются доступными обеим сторонам.";
  }
}
