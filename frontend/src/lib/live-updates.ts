/**
 * Что каждая страница перечитывает по событиям сокета (ТЗ §8).
 *
 * Модуль чистый: ни React, ни socket.io. Здесь только два решения, и оба
 * стоят того, чтобы их проверял тест, а не глаз по разметке:
 *
 * 1. Какие события какому экрану важны. Ошибиться легко в обе стороны: забыть
 *    событие — экран замрёт, добавить лишнее — страница будет перечитываться
 *    на каждый чих.
 * 2. Что делать, когда событий приходит пачка. Одно действие рождает их
 *    несколько (принятие предложения — статус заказа, статусы проигравших
 *    предложений и уведомления), а перечитывать надо один раз.
 */

import { NotificationType, socketEvents, type SocketEvent } from "@/lib/types";

/**
 * Карточка заказа. Всё, что меняет её содержимое: статус, предложения, файлы
 * сдач и уточнённая площадь.
 *
 * `notification:created` в списке ради одного случая — удаления заказа.
 * Своего события у него нет (ТЗ §8), и без уведомления открытая карточка
 * удалённого заказа осталась бы живой страницей с кнопками, которые отвечают
 * 404. Остальные уведомления отсеивает `acceptsOrderDetailEvent`.
 */
export const ORDER_DETAIL_EVENTS: readonly SocketEvent[] = [
  socketEvents.orderStatusChanged,
  socketEvents.offerCreated,
  socketEvents.offerUpdated,
  socketEvents.offerStatusChanged,
  socketEvents.orderFilesUpdated,
  socketEvents.orderAreaVerified,
  socketEvents.notificationCreated,
];

/**
 * Список заказов клиента. В таблице видны статус, подрядчик, цена и срок —
 * всё это меняется ровно переходом статуса, который приходит клиенту
 * в его личную комнату.
 */
export const ORDERS_LIST_EVENTS: readonly SocketEvent[] = [
  socketEvents.orderStatusChanged,
];

/**
 * Мои предложения (компания). Статус предложения меняет клиент — своим
 * решением, — и об этом компании приходит `offer:status_changed`.
 *
 * `notification:created` здесь нужен: заказ могли удалить, и тогда никакого
 * события про предложение не будет вовсе (ТЗ §8), а строка из списка должна
 * исчезнуть.
 */
export const COMPANY_OFFERS_EVENTS: readonly SocketEvent[] = [
  socketEvents.offerStatusChanged,
  socketEvents.notificationCreated,
];

/**
 * Лента доступных заказов. Новый заказ приходит broadcast'ом в `company-feed`,
 * удалённый — уведомлением, но только той компании, чьё предложение было в игре.
 *
 * Два случая лента вживую не догоняет, и оба намеренно: заказ, который взяла
 * другая компания, и заказ, удалённый клиентом до того, как эта компания
 * успела предложиться. В обоих компания посторонняя, а событие о чужом
 * движении заказа ей не адресуется вовсе (ТЗ §4.1) — строка исчезнет при
 * следующем открытии ленты, а попытка предложиться по ней даст честный отказ.
 */
export const COMPANY_FEED_EVENTS: readonly SocketEvent[] = [
  socketEvents.orderCreated,
  socketEvents.notificationCreated,
];

/**
 * Раздел «Документы» (ТЗ §7). Список меняется от двух вещей, и обе здесь.
 *
 * `order:files_updated` — исполнитель загрузил файлы сдачи. Событие приходит
 * клиенту в личную комнату (ТЗ §8), то есть вживую список пополняется у него;
 * вкладке самого исполнителя событие о своём действии не адресуется.
 *
 * `offer:status_changed` — клиент принял предложение, и компания стала
 * стороной сделки: раздел показывает ей файлы заказа только с этого момента
 * (`buildDocumentsWhere` на backend). Без события её список оставался бы
 * пустым до перезагрузки страницы.
 *
 * Чего этот набор не догоняет — удаления заказа: своего события у него нет
 * (ТЗ §8, `CLAUDE.md` §7), а уведомление уходит только компаниям с активным
 * предложением, у которых файлов по этому заказу и не было. У клиента,
 * удалившего заказ в соседней вкладке, строки его файлов останутся до
 * ближайшего перечитывания.
 */
export const DOCUMENTS_EVENTS: readonly SocketEvent[] = [
  socketEvents.orderFilesUpdated,
  socketEvents.offerStatusChanged,
];

/**
 * Колокольчик в шапке и раздел «Уведомления» (ТЗ §7).
 *
 * Событий про заказ здесь нет намеренно: уведомление создаётся той же
 * транзакцией, что и переход (ТЗ §8), и приходит своим событием с готовой
 * строкой. Слушать оба значило бы дважды обновлять счётчик на одно действие,
 * а событие про заказ вдобавок не означает уведомления: движение чужого
 * предложения в комнату заказа приходит, а записи в БД не создаёт.
 */
export const NOTIFICATIONS_EVENTS: readonly SocketEvent[] = [
  socketEvents.notificationCreated,
];

/**
 * Идентификатор заказа из нагрузки события.
 *
 * Нужен фильтр, а не доверие: в личную комнату пользователя приходят события
 * по **всем** его заказам, и открытая карточка одного заказа обязана
 * пропускать мимо события про соседний.
 *
 * `null` — у события нет заказа (`notification:created`) либо нагрузка
 * не той формы, что мы ждём.
 */
export function eventOrderId(payload: unknown): string | null {
  const value: unknown = (payload as { orderId?: unknown } | null)?.orderId;

  return typeof value === "string" && value.length > 0 ? value : null;
}

/**
 * Что из событий важно открытой карточке заказа.
 *
 * Обычные события отбираются по заказу: в личную комнату приходит движение
 * по **всем** заказам пользователя.
 *
 * Уведомление об удалении заказа — исключение: `orderId` у него `null`
 * (ТЗ §3, отступление в `CLAUDE.md` §7), то есть узнать, тот ли это заказ,
 * нельзя в принципе. Поэтому карточка перечитывается на любое такое
 * уведомление: удаляют заказы редко, а цена ошибки — один лишний запрос,
 * тогда как без этого компания продолжала бы работать со страницей заказа,
 * которого уже нет.
 */
export function acceptsOrderDetailEvent(orderId: string, payload: unknown): boolean {
  return eventOrderId(payload) === orderId || isOrderDeleted(payload);
}

function isOrderDeleted(payload: unknown): boolean {
  const notification = (payload as { notification?: { type?: unknown } } | null)
    ?.notification;

  return notification?.type === NotificationType.ORDER_DELETED;
}

/** Сколько ждать продолжения пачки, прежде чем перечитывать. */
export const BURST_DELAY_MS = 150;

/** Отложенный запуск, объединяющий пачку событий в один вызов. */
export interface Burst {
  /** Событие пришло: запустить через паузу, а если уже запланировано — подождать. */
  schedule: () => void;
  /** Уход со страницы: запланированное не выполнять. */
  cancel: () => void;
}

/**
 * Одно действие — один перечит.
 *
 * Таймер **не** продлевается каждым новым событием: иначе плотный поток
 * (например, компания грузит файлы один за другим) откладывал бы обновление
 * бесконечно. Первое событие назначает время, остальные до него — попутчики.
 */
export function createBurst(run: () => void, delay: number = BURST_DELAY_MS): Burst {
  let timer: ReturnType<typeof setTimeout> | null = null;

  return {
    schedule() {
      if (timer !== null) return;

      timer = setTimeout(() => {
        timer = null;
        run();
      }, delay);
    },
    cancel() {
      if (timer === null) return;

      clearTimeout(timer);
      timer = null;
    },
  };
}
