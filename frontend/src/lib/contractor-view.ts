/**
 * Как показывается компания в каталоге подрядчиков (ТЗ §7).
 *
 * Модуль чистый: ни React, ни fetch. Компоненты каталога только рисуют то,
 * что здесь собрано, — правило плюрализации проверяется тестом, а не
 * разглядыванием экрана.
 *
 * Двух вещей здесь нет намеренно: место (`formatLocation` в `lib/format.ts`)
 * и контакты (`lib/contacts.ts`) показываются так же у заказчика на карточке
 * заказа, и обе живут там, где их видят оба экрана.
 */

import { pluralRu } from "@/lib/plural";

/**
 * «3 завершённых заказа» — с русской плюрализацией.
 *
 * Ноль отдельным текстом: «0 завершённых заказов» читается как показатель,
 * хотя означает всего лишь «компания новая».
 */
export function completedOrdersText(count: number): string {
  if (count === 0) return "Пока нет завершённых заказов";

  return `${count} ${pluralRu(count, ORDER_FORMS)}`;
}

/** Правило выбора формы — общее (`lib/plural.ts`), здесь только сами слова. */
const ORDER_FORMS = [
  "завершённый заказ",
  "завершённых заказа",
  "завершённых заказов",
] as const;

